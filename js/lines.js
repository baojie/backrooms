// `ctx` = { nearestEntityDist, sanity, hp, speedBoost, currentLevel }
export function pickCompanionLine(speakerName, ctx) {
  const lib = COMPANION_LINE_LIB[speakerName];
  if (!lib) return '……';
  const { nearestEntityDist = Infinity, sanity = 1, hp = 1, speedBoost = 0, currentLevel = 0 } = ctx || {};
  const inFear = nearestEntityDist < 9 || sanity < 0.35 || hp < 0.4;
  const inSafe = nearestEntityDist > 22 && sanity > 0.85 && hp > 0.85;
  const justAteAlmond = speedBoost > 5;

  let pool;
  if (justAteAlmond && lib.item.length && Math.random() < 0.6) pool = lib.item;
  else if (inFear && lib.fear.length && Math.random() < 0.7)   pool = lib.fear;
  else if (inSafe && lib.safe.length && Math.random() < 0.5)   pool = lib.safe;
  else if (Math.random() < 0.35 && lib.floor[currentLevel] && lib.floor[currentLevel].length)
    pool = lib.floor[currentLevel];
  else pool = lib.generic;
  return pool[Math.floor(Math.random() * pool.length)];
}

