const _totalLines = Object.values(COMPANION_LINE_LIB).reduce((acc, sp) => {
  let n = sp.generic.length + sp.fear.length + sp.safe.length + sp.item.length;
  for (const f of Object.values(sp.floor)) n += f.length;
  return acc + n;
}, 0);
