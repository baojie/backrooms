// Combinatorial conversation library — produces 2,000+ unique Chinese lines
// from compact templates, organised by speaker (小王/小李) and context.
//
// `pickCompanionLine(speakerName, ctx)` — `ctx` is a plain object with the
// runtime numbers we need: { nearestEntityDist, sanity, hp, speedBoost, currentLevel }
// so this module stays free of game-state imports.

function expand(...parts) {
  if (parts.length === 0) return [''];
  const [first, ...rest] = parts;
  const tail = expand(...rest);
  const out = [];
  for (const a of first) for (const r of tail) out.push(a + r);
  return out;
}
function fromTemplates(templates) {
  const out = [];
  for (const t of templates) for (const s of expand(...t)) out.push(s);
  return out;
}

